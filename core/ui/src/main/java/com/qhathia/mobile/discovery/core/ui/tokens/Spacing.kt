package com.qhathia.mobile.discovery.core.ui.tokens

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Centralized spacing scale for the Discovery design system. Use these tokens instead of arbitrary
 * `dp` values so the spacing rhythm stays consistent across screens.
 */
object Spacing {
    val xs: Dp = 4.dp
    val sm: Dp = 8.dp
    val md: Dp = 16.dp
    val lg: Dp = 24.dp
    val xl: Dp = 32.dp
}
